"""Write the client's submission/placement.yaml from config/twincheck.yaml, so the operator's layout and
our pick points and bins always agree.

    python cell_policy/make_placement.py --out <client>/submission/placement.yaml               # same layout
    python cell_policy/make_placement.py --out ... --rollouts 10 --nudge-mm 30 --seed 1         # different

--nudge-mm moves every part a random distance up to that far from its nominal pick point, with a random
yaw, per rollout: the real-cell version of the "nudged part" induced failure. A blind program (baseline,
watch) reaches for the nominal point; guide reaches for what the camera sees. Set the same objects/layout
values in submission.yaml ("different" when nudging). The printed offsets are the ground truth.
"""
from __future__ import annotations

import argparse
import math
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "twincheck_core"))
from twincheck_core import load_config  # noqa: E402


def layout(cfg, rng: random.Random | None, nudge_mm: float, heads: bool = False) -> tuple[dict, list[str]]:
    """Part centres (what the policy aims at, and what the twin spawns). heads=True gives the operator's
    convention instead: a screw's position is its head and its yaw points to its tip, so the head sits half
    a length back from the centre along the yaw."""
    objects: dict[str, list] = {}
    notes = []
    for i, job in enumerate(cfg.raw["cell"]["sequence"], 1):
        p = cfg.pick_points[job["pick_point"]]
        x, y, yaw = p.x_mm, p.y_mm, p.yaw_deg
        if rng and nudge_mm > 0:
            r, a = nudge_mm * math.sqrt(rng.random()), rng.uniform(0, 2 * math.pi)
            x, y, yaw = x + r * math.cos(a), y + r * math.sin(a), rng.uniform(-45, 45)
            notes.append(f"job {i} {job['cls']}: {r:.0f} mm off nominal")
        if heads and job["cls"] == "screw":
            half = cfg.objects["screw"].length_mm / 2
            x, y = x - half * math.cos(math.radians(yaw)), y - half * math.sin(math.radians(yaw))
        objects.setdefault(job["cls"], []).append([round(x), round(y), round(yaw)])
    # only the bins this sequence sorts into: the operator sets up nothing we don't use
    used = dict.fromkeys(cfg.objects[job["cls"]].target_bin for job in cfg.raw["cell"]["sequence"])
    objects["bin"] = [[round(cfg.bins[b].center.x_mm), round(cfg.bins[b].center.y_mm)] for b in used]
    return objects, notes


def to_yaml(rollouts: list[tuple[dict, list[str]]]) -> str:
    lines = ["# Generated by cell_policy/make_placement.py from config/twincheck.yaml. Do not edit by hand.",
             "# x, y mm in the robot frame, yaw deg. Order of each list = the order the policy picks them.",
             "# A screw's position is its head and its yaw points to its tip (we grasp its middle).",
             "rollouts:"]
    for k, (objects, notes) in enumerate(rollouts, 1):
        lines.append(f"  - objects:                       # rollout {k}" + (f"  ({'; '.join(notes)})" if notes else ""))
        for name, poses in objects.items():
            lines.append(f"      {name}: {poses if len(poses) > 1 else poses[0]}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--rollouts", type=int, default=1, help="1 = the same layout every rollout")
    ap.add_argument("--nudge-mm", type=float, default=0.0)
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    cfg = load_config()
    rng = random.Random(a.seed)
    rollouts = [layout(cfg, rng if a.nudge_mm else None, a.nudge_mm, heads=True) for _ in range(a.rollouts)]
    Path(a.out).write_text(to_yaml(rollouts))
    print(f"wrote {a.out}: {a.rollouts} rollout(s), nudge up to {a.nudge_mm:.0f} mm, seed {a.seed}")
    for k, (_, notes) in enumerate(rollouts, 1):
        if notes:
            print(f"  rollout {k}: " + "; ".join(notes))


if __name__ == "__main__":
    main()
